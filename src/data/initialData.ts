// Reliable image helper that repairs legacy /src/assets paths and ensures fallback
export const getValidImageUrl = (url?: string, fallback = BEDSHEET_IMAGE): string => {
  if (!url || typeof url !== 'string' || url.trim() === '') return fallback;
  const trimmed = url.trim();
  // Ensure paths starting with uploads/ or images/ have leading slash
  if (trimmed.startsWith('uploads/')) return '/' + trimmed;
  if (trimmed.startsWith('images/')) return '/' + trimmed;
  // If it is a base64 data URL, blob, uploaded file, root-relative or external HTTP(S) URL, keep it exactly as is
  if (
    trimmed.startsWith('data:') || 
    trimmed.startsWith('blob:') || 
    trimmed.startsWith('http://') || 
    trimmed.startsWith('https://') || 
    trimmed.startsWith('/uploads/') ||
    trimmed.startsWith('/images/') ||
    trimmed.startsWith('/')
  ) {
    return trimmed;
  }
  if (trimmed.includes('hero_cottonella_bedroom')) return HERO_IMAGE;
  if (trimmed.includes('product_bedsheet_blossom')) return BEDSHEET_IMAGE;
  if (trimmed.includes('product_pouch_floral')) return POUCH_IMAGE;
  if (trimmed.includes('product_pillow_cozy')) return PILLOW_IMAGE;
  if (trimmed.includes('collection_spring_banner')) return COLLECTION_BANNER;
  if (trimmed.startsWith('/src/assets/images/')) {
    return trimmed.replace('/src/assets/images/', '/images/');
  }
  return trimmed;
};

